def ts(t):
    t = max(0.0, t)
    return '%02d:%02d' % (int(t // 60), int(t % 60))

def tags_of(text):
    tg = re.findall(r'\[([^\]]+)\]', text)
    out = []
    for g in tg:
        ru = TAGS.get(g)
        if ru and ru not in out and ru != 'пауза':
            out.append(ru)
    return ', '.join(out)

def main():
    ep = episode01.build()
    L = []
    L.append('# STICKMAN: BREAKPOINT\n## Сезон 1 «Черновик» · Серия 1 — «Обычный вторник»\n')
    L.append('**Хронометраж:** %s · таймкоды совпадают с файлом `STICKMAN_BREAKPOINT_S01E01.mp4`.\n' % ts(ep.duration))
    L.append('**Логлайн.** Ленивый семнадцатилетний Рэй проживает самый обычный вторник в северном городе Норден, '
             'пока разбитый телефон не собирается обратно у него на глазах, а за ним не начинают следить институт на холме и человек в пальто.\n')
    L.append('**Голоса:** ' + ', '.join('%s — %s' % (v[0], v[1]) for k, v in LN.CAST.items()) + ' (ElevenLabs, eleven_v4).\n')
    L.append('**Музыка и звук:** Soundza (AI-музыка Lyria/Stable, каталог и AI-генерация эффектов) + процедурный синтез (сердцебиение, звон в ушах).\n')
    L.append('---\n')
    subs = sorted(ep.subs, key=lambda s: s[0])
    for sc in ep.scenes:
        if sc['id'] == 'OP':
            pass
        L.append('### %s  ·  [%s – %s]  ·  %s' % ({'0': 'Холодное открытие', 'OP': 'Опенинг', 'ED': 'Эндинг', 'PC': 'Сцена после титров',
                                                    'PV': 'Превью следующей серии'}.get(sc['id'], 'Сцена %s. %s' % (sc['id'], sc['title'])),
                                                   ts(sc['t0']), ts(sc['t1']), sc['place']))
        L.append('')
        if sc.get('desc'):
            L.append('*%s*\n' % sc['desc'])
        vis = VIS.get(sc['id'])
        if vis:
            L.append('**Визуальные моменты:**')
            for v in vis:
                L.append('- ' + v)
            L.append('')
        rows = [s for s in subs if sc['t0'] <= s[0] < sc['t1']]
        if rows:
            L.append('**Диалоги:**\n')
            L.append('| Время | Персонаж | Реплика | Эмоция / подача |')
            L.append('|---|---|---|---|')
            for (a, b, who, txt, style) in rows:
                lid = next((k for k, v in LN.L.items() if LN.clean(v[1]) == txt and v[0] == who), None)
                emo = tags_of(LN.L[lid][1]) if lid else ''
                name = LN.CAST[who][0] + (' (з/к)' if style == 'vo' else '')
                L.append('| %s | %s | %s | %s |' % (ts(a), name, txt.replace('|', '/'), emo))
            L.append('')
        if sc['id'] == 'EYE':
            pass
        L.append('---\n')
    L.append(HOOK + '\n')
    path = os.path.join(ROOT, 'docs', 'episode01_script.md')
    open(path, 'w').write('\n'.join(L))
    print('wrote', path, 'scenes', len(ep.scenes), 'lines', len(subs))

if __name__ == '__main__':
    main()
