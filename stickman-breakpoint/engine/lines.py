TAG_RE = re.compile(r"\[[^\]]*\]\s*")

def clean(text):
    """Текст реплики без режиссёрских тегов — для субтитров и сценария."""
    return TAG_RE.sub('', text).strip()

def speaker(i):
    return L[i][0]

def batches(max_lines=9):
    """Группирует реплики по голосу в пакеты (порядок сохраняется) для озвучки."""
    order = list(L.keys())
    by = {}
    for i in order:
        by.setdefault(L[i][0], []).append(i)
    out = []
    for who, ids in by.items():
        for k in range(0, len(ids), max_lines):
            out.append((who, ids[k:k + max_lines]))
    return out

