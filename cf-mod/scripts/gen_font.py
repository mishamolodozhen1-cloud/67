atlas = bytearray(AW * AH)
for code in range(32, 127):
    ch  = chr(code)
    rows = FONT.get(ch, FONT[' '])
    col, row = (code - 32) % COLS, (code - 32) // COLS
    ox, oy = col * GW, row * GH
    for ry, bits in enumerate(rows):
        for bx in range(5):
            if bits & (1 << (4 - bx)):
                for sy in range(2):
                    for sx in range(2):
                        x = ox + 1 + bx * 1 + sx
                        y = oy + 2 + ry * 1 + sy
                        if 0 <= x < AW and 0 <= y < AH:
                            atlas[y * AW + x] = 255

(OUT / "inter_18.r8").write_bytes(bytes(atlas))

base_px = 14
metrics = bytearray()
metrics += struct.pack("<HHHH", AW, AH, base_px, 0)
for code in range(128):
    if 32 <= code < 127:
        col, row = (code - 32) % COLS, (code - 32) // COLS
        u0 = col * GW / AW
        v0 = row * GH / AH
        u1 = (col + 1) * GW / AW
        v1 = (row + 1) * GH / AH
        w_, h_, ox_, oy_, adv, base = GW, GH, 0, 0, GW, base_px
    else:
        u0=v0=u1=v1=w_=h_=ox_=oy_=adv=base=0
    metrics += struct.pack("<10f", u0, v0, u1, v1, w_, h_, ox_, oy_, adv, base)

(OUT / "metrics.bin").write_bytes(bytes(metrics))
print("atlas:", AW, "x", AH, "bytes:", len(atlas))
